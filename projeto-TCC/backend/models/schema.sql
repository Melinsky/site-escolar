CREATE TABLE IF NOT EXISTS app_migrations(name TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS cursos (
 id SERIAL PRIMARY KEY, nome VARCHAR(100) NOT NULL, descricao TEXT DEFAULT '',
 duracao VARCHAR(50) DEFAULT '', turno VARCHAR(50) DEFAULT '', certificacao VARCHAR(100) DEFAULT '',
 vagas INTEGER DEFAULT 0 CHECK(vagas >= 0), categoria VARCHAR(100) DEFAULT '',
 sobre TEXT DEFAULT '', modulos TEXT DEFAULT '', habilidades TEXT DEFAULT '', carreira TEXT DEFAULT '',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE cursos ADD COLUMN IF NOT EXISTS sobre TEXT DEFAULT '';
ALTER TABLE cursos ADD COLUMN IF NOT EXISTS modulos TEXT DEFAULT '';
ALTER TABLE cursos ADD COLUMN IF NOT EXISTS habilidades TEXT DEFAULT '';
ALTER TABLE cursos ADD COLUMN IF NOT EXISTS carreira TEXT DEFAULT '';
CREATE TABLE IF NOT EXISTS eventos (
 id SERIAL PRIMARY KEY, titulo VARCHAR(200) NOT NULL, descricao TEXT DEFAULT '', data_evento DATE,
 hora_inicio VARCHAR(20) DEFAULT '', local_evento VARCHAR(200) DEFAULT '', tipo VARCHAR(50) DEFAULT 'evento',
 destaque BOOLEAN DEFAULT FALSE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS avisos (
 id SERIAL PRIMARY KEY, titulo VARCHAR(200) NOT NULL, descricao TEXT DEFAULT '', tipo VARCHAR(50) DEFAULT 'informativo',
 urgente BOOLEAN DEFAULT FALSE, data_publicacao DATE DEFAULT CURRENT_DATE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS comunicados (
 id SERIAL PRIMARY KEY, titulo VARCHAR(200) NOT NULL, descricao TEXT DEFAULT '', tag VARCHAR(50) DEFAULT 'novidade',
 data_publicacao DATE DEFAULT CURRENT_DATE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS galeria (
 id SERIAL PRIMARY KEY, titulo VARCHAR(200) NOT NULL, descricao TEXT DEFAULT '', caminho_imagem VARCHAR(500) NOT NULL,
 ordem INTEGER DEFAULT 0 CHECK(ordem >= 0), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS professores (
 id SERIAL PRIMARY KEY, nome VARCHAR(200) NOT NULL, area VARCHAR(100) NOT NULL,
 disciplina TEXT DEFAULT '', sigla VARCHAR(10) DEFAULT '', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS contato_mensagens (
 id SERIAL PRIMARY KEY, nome VARCHAR(200) NOT NULL, email VARCHAR(200) NOT NULL, assunto VARCHAR(200) NOT NULL,
 mensagem TEXT NOT NULL, lida BOOLEAN DEFAULT FALSE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS escola_dados (
 id SERIAL PRIMARY KEY, campo VARCHAR(100) UNIQUE NOT NULL, valor TEXT NOT NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS usuarios (
 id SERIAL PRIMARY KEY, nome VARCHAR(100) NOT NULL, email VARCHAR(200) UNIQUE NOT NULL,
 senha_hash TEXT NOT NULL, papel TEXT NOT NULL CHECK(papel IN ('admin','editor')), ativo BOOLEAN DEFAULT TRUE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS sessoes (
 token_hash TEXT PRIMARY KEY, usuario_id INTEGER REFERENCES usuarios(id) ON DELETE CASCADE,
 csrf TEXT NOT NULL, expira TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS auditoria (
 id SERIAL PRIMARY KEY, usuario_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
 autor TEXT NOT NULL, acao TEXT NOT NULL, recurso TEXT NOT NULL, registro TEXT,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS sessoes_expira ON sessoes(expira);
